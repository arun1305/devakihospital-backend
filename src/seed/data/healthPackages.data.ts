function ta(inclusions: string[]): string[] {
  return inclusions.map((item) => {
    const translated = TEST_NAME_TA[item];
    if (!translated) {
      throw new Error(`Missing Tamil translation for test/service: "${item}"`);
    }
    return translated;
  });
}

